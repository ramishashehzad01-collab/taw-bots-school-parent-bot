-- School Parent Bot - reference Supabase schema
-- IMPORTANT:
-- 1) This is a clean, credential-free reference schema reconstructed from the
--    workflow's required fields and the project setup notes.
-- 2) If you already have these tables, DO NOT blindly recreate or overwrite them.
--    Compare the columns/types with your existing Supabase project first.
-- 3) No real parent/student records or phone numbers are included in this file.

CREATE TABLE IF NOT EXISTS public.parents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id TEXT NOT NULL UNIQUE,
    full_name TEXT NOT NULL,
    phone TEXT NOT NULL UNIQUE,
    email TEXT,
    telegram_chat_id TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.students (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id TEXT NOT NULL UNIQUE,
    first_name TEXT NOT NULL,
    last_name TEXT,
    date_of_birth DATE,
    gender TEXT,
    class_name TEXT NOT NULL,
    section TEXT NOT NULL,
    roll_number TEXT,
    admission_date DATE,
    current_status TEXT DEFAULT 'Active',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.parent_students (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id BIGINT NOT NULL REFERENCES public.parents(id) ON DELETE CASCADE,
    student_id BIGINT NOT NULL REFERENCES public.students(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT parent_students_unique_link UNIQUE (parent_id, student_id)
);

CREATE TABLE IF NOT EXISTS public.fees (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES public.students(id) ON DELETE CASCADE,
    fee_month TEXT NOT NULL,
    total_fee NUMERIC(12, 2) NOT NULL DEFAULT 0,
    paid_amount NUMERIC(12, 2) NOT NULL DEFAULT 0,
    pending_amount NUMERIC(12, 2) NOT NULL DEFAULT 0,
    payment_status TEXT,
    payment_date DATE,
    due_date DATE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.timetables (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_name TEXT NOT NULL,
    section TEXT NOT NULL,
    day_of_week TEXT NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    subject TEXT NOT NULL,
    teacher TEXT,
    room TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.notices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    message TEXT NOT NULL,
    target_class TEXT,
    target_section TEXT,
    notice_type TEXT,
    publish_date TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    is_broadcasted BOOLEAN NOT NULL DEFAULT FALSE
);

-- Backward-compatible migration for databases where notices already exists.
ALTER TABLE public.notices
    ADD COLUMN IF NOT EXISTS is_broadcasted BOOLEAN NOT NULL DEFAULT FALSE;

-- Helpful indexes for the workflow's lookup patterns.
CREATE INDEX IF NOT EXISTS idx_parents_phone ON public.parents(phone);
CREATE INDEX IF NOT EXISTS idx_parent_students_parent_id ON public.parent_students(parent_id);
CREATE INDEX IF NOT EXISTS idx_parent_students_student_id ON public.parent_students(student_id);
CREATE INDEX IF NOT EXISTS idx_fees_student_id ON public.fees(student_id);
CREATE INDEX IF NOT EXISTS idx_timetables_class_section_day
    ON public.timetables(class_name, section, day_of_week);
CREATE INDEX IF NOT EXISTS idx_notices_active_broadcast_date
    ON public.notices(is_active, is_broadcasted, publish_date DESC);

